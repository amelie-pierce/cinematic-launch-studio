// Collect capture meta (frame count + per-frame focus boxes) into src/meta.ts, and bake grain tiles.
import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';

const root = path.resolve(import.meta.dirname, '..');
const framesDir = path.resolve(root, '../capture/frames');
const out = {};
for (const app of fs.readdirSync(framesDir)) {
  const mp = path.join(framesDir, app, 'meta.json');
  if (!fs.existsSync(mp) || app.startsWith('bench')) continue;
  const m = JSON.parse(fs.readFileSync(mp, 'utf8'));
  const r = (v) => Math.round(v);
  out[app] = {
    frames: m.frames,
    marks: m.marks,
    focus: m.focus.map((b) => (b ? { x: r(b.x), y: r(b.y), width: r(b.width), height: r(b.height) } : null)),
    presses: m.presses ?? [],
    keys: m.keys ?? [],
  };
}
fs.writeFileSync(
  path.join(root, 'src/meta.ts'),
  `// generated by scripts/sync-meta.mjs\nexport const META: Record<string, { frames: number; marks: { name: string; frame: number }[]; focus: ({ x: number; y: number; width: number; height: number } | null)[]; presses: number[]; keys: number[] }> = ${JSON.stringify(out)};\n`,
);
console.log('meta for', Object.keys(out).join(', '));

// grain tiles: 512x512 grey noise PNGs, fixed seeds
const gdir = path.join(root, 'public/grain');
fs.mkdirSync(gdir, { recursive: true });
const crcT = new Uint32Array(256).map((_, n) => { let c = n; for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1; return c >>> 0; });
const crc = (buf) => { let c = 0xffffffff; for (const b of buf) c = crcT[(c ^ b) & 255] ^ (c >>> 8); return (c ^ 0xffffffff) >>> 0; };
const chunk = (type, data) => { const len = Buffer.alloc(4); len.writeUInt32BE(data.length); const td = Buffer.concat([Buffer.from(type), data]); const c = Buffer.alloc(4); c.writeUInt32BE(crc(td)); return Buffer.concat([len, td, c]); };
for (let t = 0; t < 8; t++) {
  let s = 0x9e3779b9 ^ (t * 7919);
  const rnd = () => { s = (s + 0x6d2b79f5) | 0; let x = Math.imul(s ^ (s >>> 15), 1 | s); x = (x + Math.imul(x ^ (x >>> 7), 61 | x)) ^ x; return ((x ^ (x >>> 14)) >>> 0) / 4294967296; };
  const N = 512, raw = Buffer.alloc((N + 1) * N);
  for (let y = 0; y < N; y++) { raw[y * (N + 1)] = 0; for (let x = 0; x < N; x++) { const g = (rnd() + rnd() + rnd()) / 3; raw[y * (N + 1) + 1 + x] = Math.round(g * 255); } }
  const ihdr = Buffer.alloc(13); ihdr.writeUInt32BE(N, 0); ihdr.writeUInt32BE(N, 4); ihdr[8] = 8; ihdr[9] = 0; ihdr[10] = 0; ihdr[11] = 0; ihdr[12] = 0;
  const png = Buffer.concat([Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]), chunk('IHDR', ihdr), chunk('IDAT', zlib.deflateSync(raw)), chunk('IEND', Buffer.alloc(0))]);
  fs.writeFileSync(path.join(gdir, `g${t}.png`), png);
}
